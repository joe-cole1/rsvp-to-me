export type TemplateOverrides = {
  subject?: string;
  body?: string;
} & Partial<TemplateToggles>;

export function mergedToggles(
  id: TemplateId,
  overrides?: Partial<TemplateToggles>
): TemplateToggles {
  const applicable = new Set(EMAIL_TEMPLATE_META[id].toggles);
  const result = { ...DEFAULT_TOGGLES };
  for (const key of Object.keys(result) as TemplateToggleKey[]) {
    if (applicable.has(key) && overrides?.[key] !== undefined) {
      result[key] = overrides[key]!;
    }
  }
  return result;
}

/**
 * Build a fully-rendered sample of a template (subject + element) using sample
 * data — used by the admin live preview, admin test-sends, and tests.
 * `overrides` are the (possibly unsaved) admin copy/toggle settings.
 */
export async function buildSampleEmail(
  id: TemplateId,
  theme: EmailTheme,
  overrides?: TemplateOverrides,
  locale: Locale = DEFAULT_LOCALE
): Promise<{ subject: string; element: React.ReactElement }> {
  const t = await getTranslator(locale);
  const rendered = buildSampleEmailElement(id, theme, overrides, t, locale);
  return {
    ...rendered,
    element: cloneElement(rendered.element as React.ReactElement<EmailI18nProps>, {
      i18n: { locale, t },
    }),
  };
}

function buildSampleEmailElement(
  id: TemplateId,
  theme: EmailTheme,
  overrides: TemplateOverrides | undefined,
  t: NotificationTranslator,
  locale: Locale
): { subject: string; element: React.ReactElement } {
  const vars = { ...SAMPLE_VARS[id] };
  if (vars.status) vars.status = t("Email.status.GOING");
  if (vars.decision) vars.decision = t("Email.decision.approved");
  if (vars.eventDate) {
    const event = sampleEventDetails();
    vars.eventDate = formatEventDateTime(event.startAt, event.endAt, event.timezone, locale).date;
  }
  const meta = getEmailTemplateMeta(t, vars)[id];
  const subject = overrides?.subject
    ? substitutePlaceholders(overrides.subject, vars)
    : meta.defaultSubject;
  const body =
    meta.bodyEditable && overrides?.body
      ? substitutePlaceholders(overrides.body, vars)
      : meta.defaultBody;
  const toggles = mergedToggles(id, overrides);
  const event = sampleEventDetails();
  const eventUrl = `${APP_URL}/e/${event.slug}`;

  switch (id) {
    case "invite":
      return {
        subject,
        element: (
          <InviteEmail
            theme={theme}
            body={body}
            toggles={toggles}
            event={event}
            hostName="Joe"
            rsvpBaseUrl={`${eventUrl}/rsvp?invite=sample`}
            maybeEnabled
            eventUrl={eventUrl}
          />
        ),
      };
    case "rsvpConfirmation":
      return {
        subject,
        element: (
          <RsvpConfirmationEmail
            theme={theme}
            body={body}
            toggles={toggles}
            event={event}
            status="GOING"
            eventUrl={eventUrl}
            editUrl={`${eventUrl}/rsvp?token=sample-token`}
          />
        ),
      };
    case "approval":
      return {
        subject,
        element: (
          <ApprovalEmail
            theme={theme}
            toggles={toggles}
            eventTitle={event.title}
            approved
            hostMessage={t("Email.sample.hostMessage")}
            eventUrl={eventUrl}
          />
        ),
      };
    case "blast":
      return {
        subject,
        element: (
          <BlastEmail
            theme={theme}
            toggles={toggles}
            eventTitle={event.title}
            hostName="Joe"
            message={t("Email.sample.blast")}
            eventUrl={eventUrl}
          />
        ),
      };
    case "hostRsvpAlert":
      return {
        subject,
        element: (
          <HostRsvpAlertEmail
            theme={theme}
            guestName="Alex Sample"
            status="GOING"
            plusOneCount={1}
            note={t("Email.sample.note")}
            eventTitle={event.title}
            goingCount={12}
            maybeCount={3}
            noCount={2}
            guestListUrl={`${eventUrl}#guests`}
          />
        ),
      };
    case "magicLink":
      return {
        subject,
        element: (
          <MagicLinkEmail
            code="482910"
            theme={theme}
            body={body}
            magicLink={`${APP_URL}/auth/verify?token=sample-token`}
          />
        ),
      };
    case "welcome":
      return {
        subject,
        element: (
          <WelcomeEmail
            theme={theme}
            body={body}
            magicLink={`${APP_URL}/auth/verify?token=sample-token`}
          />
        ),
      };
    case "test":
      return { subject, element: <TestEmail theme={theme} body={body} /> };
    case "coHostInvite":
      return {
        subject,
        element: (
          <CoHostInviteEmail
            theme={theme}
            event={sampleEventDetails()}
            hostName="Joe"
            inviteUrl={`${APP_URL}/auth/verify-cohost?token=sample-token`}
          />
        ),
      };
  }
}
